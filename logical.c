// logical operators

// &&  logical AND ----- dui side er condition true hoite hbe 
// ||  logical OR ----  jekono ak side er condition ture hoilei hbe 
// !   logigal not ------ condition change kore dey 


#include<stdio.h>

int main () {
    int a = 20;
    int b = 40;
    int c = 50;
    printf("using && = %d\n", c>b &&  c>b );
    printf("using || = %d\n", a>b ||  b>c );
    printf("using ! = %d\n", !b>a);



    return 0;


}